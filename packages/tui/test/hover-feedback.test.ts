import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
test("visual-only hover helper does not change mouse-release/selection semantics", () => {
  const text = readFileSync(new URL("../src/ui/hover-feedback.ts", import.meta.url), "utf8")
  expect(text).toContain("hoverBackground(theme, variant)")
  expect(text).toContain("onMouseOver")
  expect(text).toContain("onMouseOut")
  expect(text).not.toContain("stopPropagation()")
  expect(text).not.toContain("onMouseUp:")
  expect(text).not.toContain("onMouseDown:")
  const link = readFileSync(new URL("../src/ui/link.tsx", import.meta.url), "utf8")
  expect(link).toContain("hover.background() ?? props.bg")
  expect(link).toContain("openUrl(props.href)")
})
test("integration project export and select controls expose visual-only feedback without changing handlers", () => {
  const integration = readFileSync(new URL("../src/component/dialog-integration.tsx", import.meta.url), "utf8")
  for (const part of ['closeHover.background()', 'customHover.background()', 'skipHover.background()', 'onMouseUp={() => select(index())}', 'onMouseUp={() => select(rows.length)}']) expect(integration).toContain(part)
  const project = readFileSync(new URL("../src/component/dialog-project.tsx", import.meta.url), "utf8")
  for (const key of ['close', 'name', 'directory', 'team', 'kind', 'retry', 'editTeams']) expect(project).toContain(`${key}Hover.background()`)
  expect(project).toContain('onMouseDown={() => focusField(fields.name)}')
  expect(project).toContain('onMouseUp={props.onClose}')
  const update = readFileSync(new URL("../src/component/dialog-update.tsx", import.meta.url), "utf8")
  expect(update).toContain('onMouseOver={hover.onMouseOver}')
  expect(update).toContain('onMouseUp={() => void button.run()}')
  const exported = readFileSync(new URL("../src/ui/dialog-export-options.tsx", import.meta.url), "utf8")
  for (const key of ['thinking', 'tools', 'sanitize', 'copy', 'export']) expect(exported).toContain(`hovers.${key}.onMouseOver`)
  expect(exported).toContain('hovers[format].onMouseOver')
  const select = readFileSync(new URL("../src/ui/dialog-select.tsx", import.meta.url), "utf8")
  expect(select).toContain('returnHover.background()')
  expect(select).toContain('clearSearchHover.background()')
})
