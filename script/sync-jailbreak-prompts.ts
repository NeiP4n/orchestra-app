// Refreshes packages/core/src/jailbreak from the upstream collection.
// The prompts are bundled with Orchestra, so enabling the Jailbreak mode needs no network.
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises"
import os from "node:os"
import path from "node:path"

const source = "https://github.com/togg53192-cmd/jailbreaks"
const root = path.join(import.meta.dir, "..")
const target = path.join(root, "packages", "core", "src", "jailbreak")
const promptsDirectory = path.join(target, "prompts")
const temporary = await mkdtemp(path.join(os.tmpdir(), "orchestra-jailbreaks-"))

const run = (command: string[]) => {
  const result = Bun.spawnSync(command, { stdout: "pipe", stderr: "pipe" })
  if (result.exitCode !== 0) throw new Error(`${command.join(" ")} failed: ${result.stderr.toString()}`)
  return result.stdout.toString().trim()
}

try {
  run(["git", "clone", "--depth", "1", source, temporary])
  const commit = run(["git", "-C", temporary, "rev-parse", "HEAD"])
  const files = (await readdir(temporary)).filter((file) => file.endsWith(".md")).sort()

  const prompts: { id: string; name: string; file: string; text: string }[] = []
  for (const file of files) {
    if (file.toLowerCase() === "readme.md") continue
    const text = (await readFile(path.join(temporary, file), "utf8")).replace(/\r\n/g, "\n").trim()
    // Ollama Modelfiles wrap the prompt in FROM/SYSTEM directives and are not system prompts.
    if (text.startsWith("FROM ")) continue
    if (text.length < 200) continue
    prompts.push({ id: slug(path.basename(file, ".md")), name: path.basename(file, ".md"), file, text })
  }

  prompts.sort((a, b) => a.id.localeCompare(b.id))
  const duplicates = prompts.filter((prompt, index) => prompts.findIndex((item) => item.id === prompt.id) !== index)
  if (duplicates.length > 0) throw new Error(`duplicate ids: ${duplicates.map((item) => item.file).join(", ")}`)

  await mkdir(promptsDirectory, { recursive: true })
  const keep = new Set(prompts.map((prompt) => `${prompt.id}.md`))
  for (const file of await readdir(promptsDirectory)) {
    if (!keep.has(file)) await rm(path.join(promptsDirectory, file), { force: true })
  }
  for (const prompt of prompts) {
    await writeFile(path.join(promptsDirectory, `${prompt.id}.md`), `${prompt.text}\n`, "utf8")
  }

  await writeFile(path.join(target, "catalog.ts"), render(commit, prompts), "utf8")
  // The mode picker runs in the client, which may not import core: it gets the names only.
  await writeFile(path.join(root, "packages", "schema", "src", "jailbreak.ts"), renderIndex(commit, prompts), "utf8")
  console.log(`wrote ${prompts.length} prompts from ${commit.slice(0, 12)} to packages/core/src/jailbreak`)
  console.log(`wrote the policy index to packages/schema/src/jailbreak.ts`)
} finally {
  await rm(temporary, { recursive: true, force: true })
}

function slug(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
}

function render(commit: string, prompts: { id: string; name: string; file: string; text: string }[]) {
  const imports = prompts
    .map((prompt, index) => `import prompt${index} from "./prompts/${prompt.id}.md" with { type: "text" }`)
    .join("\n")
  const entries = prompts
    .map(
      (prompt, index) =>
        `  { id: ${JSON.stringify(prompt.id)}, name: ${JSON.stringify(prompt.name)}, file: ${JSON.stringify(prompt.file)}, text: prompt${index} },`,
    )
    .join("\n")
  return `// Generated by script/sync-jailbreak-prompts.ts from ${source}
// Do not edit by hand. Refresh with: bun script/sync-jailbreak-prompts.ts
/// <reference path="../markdown.d.ts" />

${imports}

export interface Prompt {
  readonly id: string
  readonly name: string
  readonly file: string
  readonly text: string
}

export const source = ${JSON.stringify(source)}
export const commit = ${JSON.stringify(commit)}

export const prompts: ReadonlyArray<Prompt> = [
${entries}
]
`
}

function renderIndex(commit: string, prompts: { id: string; name: string }[]) {
  const entries = prompts
    .map((prompt) => `  { id: ${JSON.stringify(prompt.id)}, name: ${JSON.stringify(prompt.name)} },`)
    .join("\n")
  return `export * as Jailbreak from "./jailbreak.js"

// Generated by script/sync-jailbreak-prompts.ts from ${source}
// Do not edit by hand. Refresh with: bun script/sync-jailbreak-prompts.ts
//
// The prompt text stays in @orchestra/core; this is the browser-safe index of what the collection
// contains, so the mode picker can offer every bundled policy without pulling text into the client.

export interface Prompt {
  readonly id: string
  readonly name: string
}

export const source = ${JSON.stringify(source)}
export const commit = ${JSON.stringify(commit)}

export const prompts: ReadonlyArray<Prompt> = [
${entries}
]
`
}
